import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync, spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'rsp-hook-log-test-'));
process.env.RUFLO_SOURCE_PATCH_HOME = home;
const runtime = fileURLToPath(new URL('../lib/hook-failure-log/runtime.cjs', import.meta.url));
const patch = await import('../lib/hook-failure-log/patcher.mjs');
const { STABLE_LIB } = await import('../lib/cwd/paths.mjs');
fs.mkdirSync(path.join(STABLE_LIB, 'hook-failure-log'), { recursive: true });
fs.copyFileSync(runtime, path.join(STABLE_LIB, 'hook-failure-log/runtime.cjs'));
const dir = path.join(home, '.ruflo-source-patch/hook-failures');
const records = () => fs.existsSync(dir) ? fs.readdirSync(dir).flatMap(f => fs.readFileSync(path.join(dir, f), 'utf8').trim().split('\n').filter(Boolean).map(JSON.parse)) : [];
const run = code => spawnSync(process.execPath, ['--require', runtime, '-e', code], {
  env: { ...process.env, CLAUDE_PLUGIN_ROOT: '/fixture/plugin' }, encoding: 'utf8', input: 'PRIVATE_PROMPT_SENTINEL',
});
const manifest = JSON.stringify({ hooks: { Stop: [{ hooks: [{ type: 'command', command: 'node -e "process.exit(2)"', timeout: 10 }] }] } }, null, 2);
const updated = patch.patchSource(manifest);
assert.deepEqual(updated.missing, []);
assert.equal(patch.isPatched(updated.next), true);
assert.equal(patch.patchSource(updated.next).next, updated.next);
assert.equal(patch.reverseSource(updated.next), manifest);
assert.ok(patch.patchSource(updated.next.replaceAll(home, '/foreign-owner')).missing.length);
assert.equal(JSON.parse(updated.next).hooks.Stop[0].hooks[0].timeout, 10);
const result = spawnSync('/bin/sh', ['-c', JSON.parse(updated.next).hooks.Stop[0].hooks[0].command], { env: process.env });
assert.equal(result.status, 2);
let r = run("process.stdout.write(require('fs').readFileSync(0)); process.stderr.write('SECRET_STDERR_SENTINEL');");
assert.equal(r.status, 0); assert.equal(r.stdout, 'PRIVATE_PROMPT_SENTINEL'); assert.equal(r.stderr, 'SECRET_STDERR_SENTINEL');
assert.equal(records().filter(x => x.phase === 'exited' && x.status === 0).length, 0);
r = run("require('/missing/private-fixture-module.cjs')");
assert.equal(r.status, 1); assert.match(r.stderr, /MODULE_NOT_FOUND/);
assert.ok(records().some(x => x.phase === 'uncaught' && x.errorCode === 'MODULE_NOT_FOUND'));
r = run("require('child_process').spawnSync(process.execPath,['-e',\"process.stderr.write('api_key=SECRET_CHILD_SENTINEL');process.exit(7)\"],{encoding:'utf8'});process.exit(0)");
assert.equal(r.status, 0);
assert.ok(records().some(x => x.phase === 'child-failed' && x.status === 7));
r = run("require('child_process').spawnSync(process.execPath,['-e','setInterval(()=>{},1000)'],{timeout:50,killSignal:'SIGKILL'});");
assert.equal(r.status, 0);
assert.ok(records().some(x => x.phase === 'child-failed' && x.errorCode === 'ETIMEDOUT' && x.signal === 'SIGKILL'));
r = run("try{require('child_process').execFileSync(process.execPath,['-e','process.exit(9)'])}catch(e){if(e.status!==9)process.exit(1)}");
assert.equal(r.status, 0);
assert.ok(records().some(x => x.phase === 'child-threw' && x.status === 9));
const esm = path.join(home, 'esm-hook.mjs');
fs.writeFileSync(esm, "import {spawnSync} from 'node:child_process';spawnSync(process.execPath,['-e','process.exit(8)']);");
r = spawnSync(process.execPath, ['--require', runtime, esm], { env: process.env });
assert.equal(r.status, 0); assert.ok(records().some(x => x.phase === 'child-failed' && x.status === 8));
r = run("process.stderr.write('token=PRIVATE_TOKEN_SENTINEL');process.exit(2)");
assert.equal(r.status, 2); assert.equal(r.stderr, 'token=PRIVATE_TOKEN_SENTINEL');
const raw = JSON.stringify(records());
for (const text of ['PRIVATE_PROMPT_SENTINEL', 'SECRET_STDERR_SENTINEL', 'SECRET_CHILD_SENTINEL', 'PRIVATE_TOKEN_SENTINEL']) assert.ok(!raw.includes(text));
assert.equal(fs.statSync(dir).mode & 0o777, 0o700);
for (const file of fs.readdirSync(dir)) assert.equal(fs.statSync(path.join(dir, file)).mode & 0o777, 0o600);
await Promise.all(Array.from({ length: 8 }, () => new Promise(resolve => {
  const p = spawn(process.execPath, ['--require', runtime, '-e', 'process.exit(3)'], { env: process.env });
  p.on('exit', code => { assert.equal(code, 3); resolve(); });
})));
assert.equal(records().filter(x => x.phase === 'exited' && x.status === 3).length, 8);
const killed = spawn(process.execPath, ['--require', runtime, '-e', 'setInterval(()=>{},1000)'], { env: process.env });
for (let i = 0; i < 100 && !records().some(x => x.pid === killed.pid); i++) await new Promise(resolve => setTimeout(resolve, 10));
const incomplete = fs.readdirSync(dir).find(name => name.split('-')[1] === String(killed.pid));
assert.ok(incomplete);
await new Promise(resolve => { killed.on('exit', (code, signal) => { assert.equal(signal, 'SIGKILL'); resolve(); }); killed.kill('SIGKILL'); });
assert.equal(fs.readFileSync(path.join(dir, incomplete), 'utf8').trim().split('\n').length, 1);
// Simulated dead historical receipts prove bounded retention without 300 subprocesses.
for (let i = 0; i < 300; i++) fs.writeFileSync(path.join(dir, `${1000000000000 + i}-999999999-${String(i).padStart(16, '0')}.jsonl`), '{}\n', { mode: 0o600 });
run('process.exit(4)'); assert.ok(fs.readdirSync(dir).length <= 256);
const other = fs.mkdtempSync(path.join(os.tmpdir(), 'rsp-hook-log-symlink-'));
const unsafeHome = fs.mkdtempSync(path.join(os.tmpdir(), 'rsp-hook-log-home-'));
fs.mkdirSync(path.join(unsafeHome, '.ruflo-source-patch'));
fs.symlinkSync(other, path.join(unsafeHome, '.ruflo-source-patch/hook-failures'));
r = spawnSync(process.execPath, ['--require', runtime, '-e', 'process.exit(7)'], { env: { ...process.env, RUFLO_SOURCE_PATCH_HOME: unsafeHome } });
assert.equal(r.status, 7); assert.deepEqual(fs.readdirSync(other), []);
console.log('hook failure logging: reversible preload, native outcomes, missing module, child failures/timeouts, privacy, concurrency, retention, symlink refusal passed');
await import('./hook-failure-log-trust.mjs');
await import('./hook-failure-log-socket.mjs');
await import('./hook-failure-log-stdio.mjs');
